CREATE TABLE modulo_precio (
    modulo varchar(40) PRIMARY KEY,
    precio_mensual numeric(12,2) NOT NULL DEFAULT 0,
    precio_anual numeric(12,2) NOT NULL DEFAULT 0,
    se_vende_aparte boolean NOT NULL DEFAULT true,
    CONSTRAINT modulo_precio_no_negativo CHECK (precio_mensual >= 0 AND precio_anual >= 0)
);

