CREATE TABLE factura (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id bigint NOT NULL REFERENCES negocio(id),
    numero varchar(20) NOT NULL,
    plan_codigo varchar(20) NOT NULL,
    ciclo varchar(20) NOT NULL,
    periodo_desde date NOT NULL,
    periodo_hasta date NOT NULL,
    emitida_en timestamp(6) NOT NULL,
    vence_en date NOT NULL,
    total numeric(12,2) NOT NULL,
    estado varchar(20) NOT NULL,
    pagada_en timestamp(6),
    metodo_pago varchar(30),
    referencia_pago varchar(120),
    registrada_por varchar(60),
    nota varchar(300),
    CONSTRAINT uk_factura_numero UNIQUE (numero),
    CONSTRAINT factura_estado_check CHECK (estado IN ('PENDIENTE','PAGADA','ANULADA')),
    CONSTRAINT factura_total_no_negativo CHECK (total >= 0)
);
CREATE INDEX idx_factura_negocio_estado ON factura (negocio_id, estado);
CREATE UNIQUE INDEX uk_factura_negocio_periodo ON factura (negocio_id, periodo_desde) WHERE estado <> 'ANULADA';

CREATE TABLE factura_linea (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id bigint NOT NULL REFERENCES factura(id) ON DELETE CASCADE,
    concepto varchar(160) NOT NULL,
    modulo varchar(40),
    cantidad integer NOT NULL,
    precio_unitario numeric(12,2) NOT NULL,
    subtotal numeric(12,2) NOT NULL
);
CREATE INDEX idx_factura_linea_factura ON factura_linea (factura_id);

CREATE TABLE aviso_cobro (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id bigint NOT NULL REFERENCES negocio(id),
    factura_id bigint REFERENCES factura(id),
    tipo varchar(20) NOT NULL,
    mensaje varchar(300) NOT NULL,
    fecha timestamp(6) NOT NULL,
    dia date NOT NULL,
    CONSTRAINT aviso_cobro_tipo_check CHECK (tipo IN ('FACTURA_EMITIDA','RECORDATORIO','VENCIDA','ULTIMO_AVISO','SUSPENDIDO','PAGO_RECIBIDO')),
    CONSTRAINT uk_aviso_cobro_dia UNIQUE (negocio_id, factura_id, tipo, dia)
);
CREATE INDEX idx_aviso_cobro_negocio_fecha ON aviso_cobro (negocio_id, fecha);
