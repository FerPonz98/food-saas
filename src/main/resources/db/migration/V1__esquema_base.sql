ALTER TABLE platos ADD COLUMN IF NOT EXISTS descripcion varchar(255);
ALTER TABLE platos ADD COLUMN IF NOT EXISTS disponible boolean;
ALTER TABLE platos ADD COLUMN IF NOT EXISTS precio double precision DEFAULT 0 NOT NULL;
ALTER TABLE platos ADD COLUMN IF NOT EXISTS stock_disponible integer;
ALTER TABLE platos ADD COLUMN IF NOT EXISTS archivado boolean DEFAULT false NOT NULL;
ALTER TABLE platos ADD COLUMN IF NOT EXISTS imagen_version bigint;

