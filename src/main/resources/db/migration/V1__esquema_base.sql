ALTER TABLE presentaciones_plato ADD COLUMN IF NOT EXISTS precio double precision DEFAULT 0 NOT NULL;
ALTER TABLE presentaciones_plato ADD COLUMN IF NOT EXISTS stock_disponible integer;
ALTER TABLE presentaciones_plato ADD COLUMN IF NOT EXISTS plato_id bigint;

