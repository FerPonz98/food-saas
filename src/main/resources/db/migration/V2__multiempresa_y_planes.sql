CREATE TABLE plan (
    codigo varchar(20) PRIMARY KEY,
    nombre varchar(60) NOT NULL,
    descripcion varchar(240),
    orden integer NOT NULL,
    precio_mensual numeric(12,2) NOT NULL,
    precio_anual numeric(12,2) NOT NULL,
    precio_implementacion numeric(12,2) NOT NULL,
    mesas_incluidas integer,
    productos_incluidos integer,
    usuarios_incluidos integer,
    activo boolean NOT NULL DEFAULT true
);

CREATE TABLE plan_modulo (
    plan_codigo varchar(20) NOT NULL REFERENCES plan(codigo) ON DELETE CASCADE,
    modulo varchar(40) NOT NULL,
    PRIMARY KEY (plan_codigo, modulo)
);

