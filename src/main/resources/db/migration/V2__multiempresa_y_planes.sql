CREATE TABLE negocio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    nombre varchar(120) NOT NULL,
    slug varchar(40) NOT NULL,
    plan_codigo varchar(20) NOT NULL REFERENCES plan(codigo),
    estado varchar(20) NOT NULL,
    ciclo varchar(20) NOT NULL,
    inicio_suscripcion date,
    vence_en date,
    contacto_nombre varchar(120),
    contacto_telefono varchar(40),
    contacto_email varchar(120),
    notas varchar(1000),
    creado_en timestamp(6) NOT NULL,
    CONSTRAINT uk_negocio_slug UNIQUE (slug),
    CONSTRAINT negocio_estado_check CHECK (estado IN ('PRUEBA','ACTIVO','SUSPENDIDO','CANCELADO')),
    CONSTRAINT negocio_ciclo_check CHECK (ciclo IN ('MENSUAL','ANUAL'))
);

CREATE TABLE negocio_modulo (
    negocio_id bigint NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    modulo varchar(40) NOT NULL,
    habilitado boolean NOT NULL,
    PRIMARY KEY (negocio_id, modulo)
);

