ALTER TABLE llamado_mesa ADD COLUMN confirmado_por varchar(60);
CREATE INDEX idx_llamado_mesa_negocio_pendiente ON llamado_mesa (negocio_id, atendido_en, numero_mesa);

ALTER TABLE pedidos ADD COLUMN abonado double precision DEFAULT 0 NOT NULL;

CREATE TABLE solicitud_pedido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id bigint NOT NULL REFERENCES negocio(id),
    numero_mesa integer NOT NULL,
    token varchar(40) NOT NULL,
    estado varchar(20) NOT NULL,
    nombre_cliente varchar(60),
    nota varchar(200),
    total double precision NOT NULL,
    creado_en timestamp(6) NOT NULL,
    revisado_en timestamp(6),
    revisado_por varchar(60),
    motivo_rechazo varchar(200),
    pedido_id bigint REFERENCES pedidos(id),
    CONSTRAINT uk_solicitud_pedido_token UNIQUE (token),
    CONSTRAINT solicitud_pedido_estado_check CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA'))
);
CREATE INDEX idx_solicitud_pedido_negocio_estado ON solicitud_pedido (negocio_id, estado, creado_en);

CREATE TABLE solicitud_pedido_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id bigint NOT NULL REFERENCES negocio(id),
    solicitud_id bigint NOT NULL REFERENCES solicitud_pedido(id) ON DELETE CASCADE,
    plato_id bigint NOT NULL REFERENCES platos(id),
    presentacion_id bigint REFERENCES presentaciones_plato(id),
    acompanante_id bigint REFERENCES platos(id),
    cantidad integer NOT NULL,
    notas varchar(120),
    nombre varchar(255) NOT NULL,
    precio_unitario double precision NOT NULL,
    subtotal double precision NOT NULL
);
CREATE INDEX idx_solicitud_pedido_item_solicitud ON solicitud_pedido_item (solicitud_id);

CREATE TABLE pago_parcial (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id bigint NOT NULL REFERENCES negocio(id),
    pedido_id bigint NOT NULL REFERENCES pedidos(id),
    monto double precision NOT NULL,
    metodo_pago varchar(20) NOT NULL,
    persona varchar(60),
    modo varchar(20) NOT NULL,
    detalle varchar(500),
    cobrado_por varchar(60),
    fecha timestamp(6) NOT NULL,
    CONSTRAINT pago_parcial_modo_check CHECK (modo IN ('PRODUCTOS','PARTES','MONTO'))
);
CREATE INDEX idx_pago_parcial_pedido ON pago_parcial (pedido_id);
CREATE INDEX idx_pago_parcial_negocio_fecha ON pago_parcial (negocio_id, fecha);

CREATE TABLE pago_parcial_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id bigint NOT NULL REFERENCES negocio(id),
    pago_id bigint NOT NULL REFERENCES pago_parcial(id) ON DELETE CASCADE,
    detalle_pedido_id bigint NOT NULL REFERENCES detalle_pedidos(id),
    cantidad integer NOT NULL
);
CREATE INDEX idx_pago_parcial_item_pago ON pago_parcial_item (pago_id);
